def nc(c):
    return not (c.isspace() or c in PUNCT or c in ",.;:!?\"'()")


def build(n):
    """成片字幕 = 真实口播（ASR 分段）+ 提词稿校正同音错字。

    断句原则：以 ASR 的自然分段为一句（ASR 按语音停顿切，天然不会切在词中间），
    一段超过 MAXLEN 再按安全切点拆，绝不硬切。
    """
    d = json.load(io.open(os.path.join(ROOT, "draft_%d.json" % n), encoding="utf-8"))
    body = re.sub(r"\n+", "\n", TEXT[n]).strip()
    bn = "".join(c for c in body if nc(c))

    # ASR 字符时间轴
    ac, at = [], []
    for seg in d["cues"]:
        t = seg["text"].replace(" ", "")
        chars = [c for c in t if nc(c)]
        if not chars:
            continue
        a, b = seg["start"], seg["end"]
        for i, c in enumerate(chars):
            ac.append(c)
            at.append((a + (b - a) * i / len(chars), a + (b - a) * (i + 1) / len(chars)))
    asr = "".join(ac)

    # ★ 字幕正文用「提词稿校正过的 ASR 全文」，不是提词稿本身。
    #   理由：提词稿字数少于真实口播（临场发挥），若用提词稿，多讲的话就没有字幕，
    #   而字幕时间又按 ASR 走，结果就是字幕越往后越超前于口播。
    #   做法：把提词稿里正确的写法，回填到 ASR 全文的同音错字上，得到"既准又全"的正文。
    import difflib as _df
    _sm = _df.SequenceMatcher(None, bn, asr, autojunk=False)
    merged = []
    _bi = 0
    for tag, i1, i2, j1, j2 in _sm.get_opcodes():
        if tag == "equal":
            merged.append(asr[j1:j2]); _bi = i2
        elif tag == "replace":
            # 同位置：用提词稿的正确写法替换 ASR 的可能错字
            if (i2 - i1) == (j2 - j1):
                merged.append(bn[i1:i2])
            else:
                merged.append(asr[j1:j2])
            _bi = i2
        elif tag == "delete":
            _bi = i2
        elif tag == "insert":
            merged.append(asr[j1:j2])
    body = "".join(merged)
    # 砍掉下集预告（"下一讲"及其后所有内容），成片不收预告
    for _k in ("下一讲", "下一期", "下集"):
        if _k in body:
            body = body.split(_k)[0]
    bn = "".join(c for c in body if nc(c))
    sm = difflib.SequenceMatcher(None, bn, asr, autojunk=False)
    times = [None] * len(bn)          # 每个正文字符的 (t0,t1)
    last_t = at[0][0] if at else 0.0
    _skipped = 0.0                    # 已删掉的 ASR 时长（要从后续时间里抵扣）
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            for k in range(i2 - i1):
                t0, t1 = at[j1 + k]
                times[i1 + k] = (max(0.0, t0 - _skipped), max(0.05, t1 - _skipped))
            last_t = at[j2 - 1][1] - _skipped
        elif tag == "replace":
            if j2 > j1:
                a, b = at[j1][0] - _skipped, at[j2 - 1][1] - _skipped
            else:
                a, b = last_t, last_t + 0.35 * (i2 - i1)
            step = (b - a) / max(1, i2 - i1)
            for k in range(i2 - i1):
                times[i1 + k] = (a + step * k, a + step * (k + 1))
            last_t = b
        elif tag == "delete":
            # 正文里没有、ASR 里有 → 这段语音被删掉了，其时长要从后面所有时间中扣掉，
            # 这样后面的字幕才会跟着往前挪，整片才会缩短到 176s 以内。
            if j2 > j1:
                _skipped += at[j2 - 1][1] - at[j1][0]
        elif tag == "insert":
            # 正文没有、ASR 有 = 临场发挥。董事长定的规矩：临场发挥保留原话。
            # 这一段不消耗正文字符，但时间要算进去（后面字幕按真实语音走）。
            pass
    # 空洞用前后已知时间线性插值（不越出素材时长）
    dur = float(d["duration"])
    known = [i for i in range(len(bn)) if times[i] is not None]
    for i in range(len(bn)):
        if times[i] is not None:
            continue
        prev = max([k for k in known if k < i], default=None)
        nxt = min([k for k in known if k > i], default=None)
        a = times[prev][1] if prev is not None else 0.0
        b = times[nxt][0] if nxt is not None else min(dur, a + 0.3)
        if b < a:
            b = a + 0.05
        # 同段空洞均分
        seg = [k for k in range(len(bn)) if times[k] is None and
               (prev is None or k > prev) and (nxt is None or k < nxt)]
        step = (b - a) / max(1, len(seg))
        for j, k in enumerate(seg):
            times[k] = (a + step * j, a + step * (j + 1))
    # 单调化
    for i in range(1, len(times)):
        if times[i][0] < times[i - 1][1]:
            s = times[i - 1][1]
            times[i] = (s, max(s + 0.05, times[i][1]))

    # 正文 → (char, t0, t1)
    seq, bi = [], 0
    for ch in body:
        if nc(ch):
            seq.append((ch, times[bi][0], times[bi][1])); bi += 1
        else:
            seq.append((ch, None, None))

    # 断句（不切词）
    # 规则：
    #   1) 遇句末标点 。！？ → 断
    #   2) 遇逗号/顿号且已够 7 字 → 断
    #   3) 到 MAXLEN 还没遇到标点 → 回退到最近的安全切点（词边界），绝不硬切在词语中间
    #   4) 单条绝不超过 MAXLEN，超了就回退
    # 词边界参考：中文里"的、了、就、是、在、和、也、都、不"等虚词前后、数字前后、
    # 引号内外都是自然断点；英文/数字串不切断。
    SAFE_BREAK_AFTER = set("的了吗呢吧啊着过就都也还才再又要会能可以是在对把被让给从向")
    cues, cur = [], []
    for ch, a, b in seq:
        cur.append((ch, a, b))
        nl = sum(1 for c, _, _ in cur if nc(c))
        if ch == "\n" or (ch in "。！？" and nl >= 4):
            cues.append(cur); cur = []
            continue
        if ch in "，、；：" and nl >= 7:
            cues.append(cur); cur = []
            continue
        if nl >= MAXLEN:
            # 回退：从末尾往前找最近的安全切点（在虚词之后 / 标点之后）
            cut = -1
            for j in range(len(cur) - 1, max(0, len(cur) - 6), -1):
                cc = cur[j][0]
                if cc in SAFE_BREAK_AFTER or cc in "，、；：。！？":
                    cut = j + 1
                    break
            if cut <= 0:
                cut = len(cur)
            cues.append(cur[:cut])
            cur = cur[cut:]
    if cur:
        cues.append(cur)

    out = []
    for c in cues:
        txt = "".join(x[0] for x in c).replace(chr(10), "").strip(PUNCT + " ")
        tt = [(a, b) for _, a, b in c if a is not None]
        if not txt or not tt:
            continue
        out.append(dict(start=round(tt[0][0], 2), end=round(tt[-1][1], 2), text=txt))
    # 碎片合并：把"读不完的短条"并回邻句，保证每条都看得清
    # 判据：时长 < 0.9s 或 字数≤2 或 语速 > 9字/秒
    _merged = []
    for c in out:
        dur = c["end"] - c["start"]
        n = len(c["text"])
        frag = (dur < 0.9 or n <= 2 or (n / dur if dur > 0 else 99) > 9)
        if frag and _merged:
            prev = _merged[-1]
            # 并进上一句：文字接上，时间延到本条结束
            prev["text"] = prev["text"] + c["text"]
            prev["end"] = max(prev["end"], c["end"])
        elif frag and len(out) > 1:
            # 第一条就是碎片，并进下一条
            nxt = out[out.index(c) + 1] if out.index(c) + 1 < len(out) else None
            if nxt:
                nxt["text"] = c["text"] + nxt["text"]
                nxt["start"] = min(nxt["start"], c["start"])
        else:
            _merged.append(c)
    out = _merged

    # 删段后遗留的大空档要收掉：把 gap >1.2s 的部分整体前移（口播连续，字幕不许断档）
    if out:
        out[0]["start"] = out[0]["start"]
    # 不收缩空档：字幕时间必须等于真实语音时间（成片端统一除以倍速换算）
    for i in range(len(out) - 1):
        if out[i]["end"] > out[i + 1]["start"]:
            out[i]["end"] = round(out[i + 1]["start"] - 0.01, 2)
    res = dict(n=n, src=d["src"], duration=d["duration"], cues=out)
    json.dump(res, io.open(os.path.join(ROOT, "final_%d.json" % n), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    with io.open(os.path.join(ROOT, "final_%d.md" % n), "w", encoding="utf-8") as f:
        f.write("# 素材 %d 已校对字幕 %s %.1fs %d 条\n\n" % (n, d["src"], d["duration"], len(out)))
        for k, c in enumerate(out):
            f.write("%3d [%7.2f -> %7.2f] %s\n" % (k, c["start"], c["end"], c["text"]))
    return res


