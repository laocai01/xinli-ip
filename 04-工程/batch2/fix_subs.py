def split_cues(text, t0, t1):
    """按标点切 ≤MAXLEN 条；时间按字数比例分配"""
    parts, cur = [], ""
    for ch in text:
        cur += ch
        n = len(re.sub(r"[^\w]", "", cur))
        if (ch in "。！？；" and n >= 4) or (ch in "，、" and n >= 9) or n >= MAXLEN:
            parts.append(cur); cur = ""
    if cur.strip():
        parts.append(cur)
    total = sum(max(1, len(re.sub(r"[^\w]", "", p))) for p in parts)
    out, t = [], t0
    for p in parts:
        n = max(1, len(re.sub(r"[^\w]", "", p)))
        dur = (t1 - t0) * n / total
        out.append(dict(start=round(t, 2), end=round(t + dur, 2), text=p.strip("，、。 ")))
        t += dur
    if out:
        out[-1]["end"] = round(t1, 2)
    return out


def build(n):
    d = json.load(io.open(os.path.join(ROOT, "draft_%d.json" % n), encoding="utf-8"))
    cues = d["cues"]
    blocks = {b[0]: b for b in BLOCK.get(n, [])}
    out, i = [], 0
    while i < len(cues):
        if i in blocks:
            _, j, text = blocks[i]
            t0, t1 = cues[i]["start"], cues[j]["end"]
            out += split_cues(text, t0, t1)
            i = j + 1
            continue
        c = dict(cues[i])
        if i in REPL.get(n, {}):
            c["text"] = REPL[n][i]
        out.append(c)
        i += 1
    # 全局清理
    for c in out:
        c["text"] = (c["text"].replace("《", "").replace("》", "").replace("瑣", "琐")
                     .replace("。了", "了。").strip())
    clean = []
    for c in out:
        core = re.sub(r"[^\w]", "", c["text"])
        if not core:
            continue
        if clean and len(core) <= 2 and c["start"] - clean[-1]["end"] < 0.4:
            clean[-1]["text"] += c["text"]; clean[-1]["end"] = c["end"]
            continue
        clean.append(c)
    out = clean
    res = dict(n=n, src=d["src"], duration=d["duration"], cues=out)
    json.dump(res, io.open(os.path.join(ROOT, "final_%d.json" % n), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    with io.open(os.path.join(ROOT, "final_%d.md" % n), "w", encoding="utf-8") as f:
        f.write("# 素材 %d 已校对字幕  %s  %.1fs  %d 条\n\n" % (n, d["src"], d["duration"], len(out)))
        for k, c in enumerate(out):
            f.write("%3d [%7.2f -> %7.2f] %s\n" % (k, c["start"], c["end"], c["text"]))
    return res


if __name__ == "__main__":
    import sys
    for n in [int(x) for x in (sys.argv[1:] or ["1", "2", "3", "4", "5", "6"])]:
        r = build(n)
        print("final %d: cues=%d 末句 %.1fs" % (n, len(r["cues"]), r["cues"][-1]["end"]))
