def fix_text(n, text):
    """对单条文本做错字替换。

    ★ 2026-11-04：ASR 原文带逗号（"你在旅游上写着四个字,待夜在家"），
      替换前先去标点，否则"旅游上写着四个字待夜在家"匹配不上。
    """
    import re as _re
    flat = _re.sub(r"[，。！？、；：,\s]+", "", text)
    for wrong, right in FIX.get(n, []):
        if wrong in flat:
            flat = flat.replace(wrong, right)
    return flat
