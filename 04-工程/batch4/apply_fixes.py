def main():
    data = {}
    for n in range(1, 7):
        p = os.path.join(OUT, "raw_%d.json" % n)
        data[n] = json.load(open(p, encoding="utf-8"))

    log = []
    for n, old, new, why in FIX:
        if old == new:
            continue
        rows = data[n]
        hit = [i for i, r in enumerate(rows) if old in r["text"]]
        if not hit:
            log.append(dict(n=n, old=old, new=new, why=why, status="MISS"))
            continue
        for i in hit:
            rows[i]["text"] = rows[i]["text"].replace(old, new)
        log.append(dict(n=n, old=old, new=new, why=why, status="OK", segs=[rows[i]["start"] for i in hit]))

    for n in range(1, 7):
        p = os.path.join(OUT, "raw_%d.json" % n)
        with open(p, "w", encoding="utf-8") as f:
            json.dump(data[n], f, ensure_ascii=False, indent=1)
        rows = data[n]
        dur = rows[-1]["end"]
        with open(os.path.join(OUT, "raw_%d.md" % n), "w", encoding="utf-8") as f:
            f.write("# 素材 %d.mp4 转录（faster-whisper small，%.1fs）\n\n" % (n, dur))
            for r in rows:
                f.write("[%7.2f -> %7.2f] %s\n" % (r["start"], r["end"], r["text"]))

    json.dump(log, open(os.path.join(OUT, "_校对_apply_log.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    ok = sum(1 for x in log if x["status"] == "OK")
    print("applied %d / %d" % (ok, len(log)))
    for x in log:
        if x["status"] == "MISS":
            print("MISS", x["n"], x["old"])


if __name__ == "__main__":
    main()
