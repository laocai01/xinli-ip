def t2s(s):
    return "".join(T2S.get(c, c) for c in s)


PUNC = "，。！？、；：,.!?;: \u3000"
UNSURE_HINT = ["在探期", "呃"]


def norm(s):
    return "".join(c for c in s if c not in PUNC)


def apply_fix(text, bad_n, good):
    """在 text 中找 norm(bad) 对应位置替换成 good"""
    nt = norm(text)
    idx = nt.find(bad_n)
    if idx < 0:
        return text, False
    pos = [i for i, c in enumerate(text) if c not in "，。！？、；：,.!?;: \u3000"]
    i0, i1 = pos[idx], pos[idx + len(bad_n) - 1]
    return text[:i0] + good + text[i1 + 1:], True


def fix_text(n, s, log):
    s = t2s(s)
    for bad, good in FIX.get(n, []):
        s, ok = apply_fix(s, norm(bad), good)
        if ok:
            log.append((n, bad, good))
    # 标点统一：半角逗号→全角，去多余空格
    s = s.replace(",", "，")
    s = re.sub(r"\s{2,}", " ", s)
    return s.strip()


def is_trad_ratio(np_text):
    han = [c for c in np_text if "\u4e00" <= c <= "\u9fff"]
    if not han:
        return 0.0
    # 用 t2s 表里出现过的繁体字计数（近似）
    trad = sum(1 for c in han if c in T2S and T2S[c] != c)
    return trad / len(han)


def main():
    tot_log = []
    report = {}
    for n in range(1, 7):
        p = os.path.join(B4, "raw_%d.json" % n)
        segs = json.load(io.open(p, encoding="utf-8"))
        trad_before = is_trad_ratio("".join(s["text"] for s in segs))
        out = []
        for s in segs:
            t = fix_text(n, s["text"], tot_log)
            out.append(dict(start=s["start"], end=s["end"], text=t))
        json.dump(out, io.open(os.path.join(B4, "hz_corrected_%d.json" % n), "w",
                  encoding="utf-8"), ensure_ascii=False, indent=1)
        joined = "".join(s["text"] for s in out)
        trad_after = is_trad_ratio(joined)
        chars = len([c for c in joined if "\u4e00" <= c <= "\u9fff"])
        report[n] = dict(segs=len(out), chars=chars,
                         trad_before=round(trad_before, 4),
                         trad_after=round(trad_after, 4),
                         unsure=[u for u in UNSURE_HINT if u in joined])
    json.dump(tot_log, io.open(os.path.join(B4, "_fix_log.json"), "w",
              encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(report, ensure_ascii=False, indent=1))
    print("\n共修订 %d 处" % len(tot_log))
    for n, bad, good in tot_log:
        print("  [%d] %s → %s" % (n, bad, good))


if __name__ == "__main__":
    main()
